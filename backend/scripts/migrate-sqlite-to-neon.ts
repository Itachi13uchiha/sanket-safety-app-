/**
 * One-time SQLite -> Neon/PostgreSQL data migration.
 *
 * Run from the backend directory after backing up data/sanket.db:
 *   npm install pg
 *   $env:DATABASE_URL = "your rotated Neon connection string"
 *   npx tsx scripts/migrate-sqlite-to-neon.ts
 *
 * The script refuses to run if the Neon public schema already contains tables.
 * It does not delete or modify the source SQLite database.
 */
import Database from 'better-sqlite3';
import { Client } from 'pg';
import fs from 'node:fs';
import path from 'node:path';

const sqlitePath = process.env.SQLITE_PATH ?? './data/sanket.db';
const databaseUrl = process.env.DATABASE_URL;

if (!databaseUrl) {
  console.error('DATABASE_URL is missing. Set it in your terminal environment; do not commit it.');
  process.exit(1);
}
if (!fs.existsSync(sqlitePath)) {
  console.error(`SQLite database not found: ${path.resolve(sqlitePath)}`);
  process.exit(1);
}

function quoteIdent(value: string): string {
  return '"' + value.replaceAll('"', '""') + '"';
}

function postgresize(sql: string): string {
  return sql
    .replace(/\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b/gi, 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
    .replace(/\bINTEGER\b/gi, 'BIGINT')
    .replace(/\bREAL\b/gi, 'DOUBLE PRECISION');
}

async function main() {
  const source = new Database(sqlitePath, { readonly: true, fileMustExist: true });
  const violations = source.pragma('foreign_key_check') as unknown[];
  if (violations.length) {
    source.close();
    throw new Error(`Source SQLite database has ${violations.length} foreign-key violation(s); fix/inspect them before migrating.`);
  }

  const tables = source.prepare(`
    SELECT name, sql FROM sqlite_master
    WHERE type = 'table' AND name NOT LIKE 'sqlite_%' AND sql IS NOT NULL
    ORDER BY rowid
  `).all() as Array<{ name: string; sql: string }>;

  if (!tables.length) {
    source.close();
    throw new Error('No user tables found in the SQLite database.');
  }

  const indexes = source.prepare(`
    SELECT name, sql FROM sqlite_master
    WHERE type = 'index' AND sql IS NOT NULL
    ORDER BY rowid
  `).all() as Array<{ name: string; sql: string }>;

  const client = new Client({
    connectionString: databaseUrl,
    ssl: databaseUrl.includes('sslmode=require') ? { rejectUnauthorized: false } : undefined,
    connectionTimeoutMillis: 15000,
  });

  try {
    await client.connect();

    const existing = await client.query(`
      SELECT tablename FROM pg_tables
      WHERE schemaname = 'public'
      ORDER BY tablename
    `);
    if (existing.rows.length) {
      throw new Error(
        'Neon public schema is not empty (' +
        existing.rows.map((row: { tablename: string }) => row.tablename).join(', ') +
        '). For safety, no changes were made. Use a fresh/empty Neon database or review the existing tables first.',
      );
    }

    console.log(`Found ${tables.length} tables and ${indexes.length} indexes in ${path.resolve(sqlitePath)}.`);
    await client.query('BEGIN');

    // The schema was created in dependency order in Sanket's SQLite migrations.
    for (const table of tables) {
      const createSql = postgresize(table.sql);
      await client.query(createSql);
      console.log(`Created table: ${table.name}`);
    }

    const counts: Array<{ table: string; rows: number }> = [];
    for (const table of tables) {
      const columns = source.pragma(`table_info(${quoteIdent(table.name)})`) as Array<{ name: string }>;
      const columnNames = columns.map((column) => column.name);
      const rows = source.prepare(`SELECT * FROM ${quoteIdent(table.name)}`).all() as Array<Record<string, unknown>>;

      if (rows.length) {
        const namesSql = columnNames.map(quoteIdent).join(', ');
        const placeholders = columnNames.map((_, i) => '$' + (i + 1)).join(', ');
        const insertSql = `INSERT INTO ${quoteIdent(table.name)} (${namesSql}) VALUES (${placeholders})`;
        for (const row of rows) {
          await client.query(insertSql, columnNames.map((column) => row[column]));
        }
      }
      counts.push({ table: table.name, rows: rows.length });
      console.log(`Copied ${rows.length} row(s): ${table.name}`);
    }

    // Create indexes after inserts, including partial unique indexes.
    for (const index of indexes) {
      await client.query(postgresize(index.sql));
      console.log(`Created index: ${index.name}`);
    }

    // Keep identity sequences ahead of explicitly imported IDs.
    for (const table of tables) {
      const autoColumn = table.sql.match(/\b([A-Za-z_][A-Za-z0-9_]*)\s+INTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b/i)?.[1];
      if (!autoColumn) continue;
      const tableName = `public.${quoteIdent(table.name)}`;
      const col = quoteIdent(autoColumn);
      await client.query(
        `SELECT setval(pg_get_serial_sequence($1, $2), COALESCE(MAX(${col}), 1), MAX(${col}) IS NOT NULL) FROM ${quoteIdent(table.name)}`,
        [tableName, autoColumn],
      );
    }

    // Check every destination row count before committing.
    for (const expected of counts) {
      const result = await client.query(`SELECT COUNT(*)::bigint AS count FROM ${quoteIdent(expected.table)}`);
      const actual = Number(result.rows[0].count);
      if (actual !== expected.rows) {
        throw new Error(`Row-count mismatch in ${expected.table}: SQLite=${expected.rows}, Neon=${actual}`);
      }
    }

    await client.query('COMMIT');
    console.log('\nMigration completed and committed successfully.');
    console.table(counts);
    console.log('Source SQLite file was opened read-only and has not been changed.');
  } catch (error) {
    try { await client.query('ROLLBACK'); } catch { /* ignore rollback errors */ }
    throw error;
  } finally {
    source.close();
    await client.end().catch(() => undefined);
  }
}

main().catch((error: unknown) => {
  console.error('\nMigration failed:', error instanceof Error ? error.message : error);
  process.exitCode = 1;
});
